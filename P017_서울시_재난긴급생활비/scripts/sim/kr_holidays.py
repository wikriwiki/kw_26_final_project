_YEARS = {2020, 2021, 2025}


def holiday_name(d: date) -> str | None:
    return _HOLIDAYS.get(d.isoformat())


def require_covered(first: date, last: date) -> None:
    """실행기용: 시뮬 날짜의 해가 모두 표에 있어야 한다. 없으면 멈춘다(조용히 평일로 두지 않는다)."""
    missing = sorted({y for y in range(first.year, last.year + 1)} - _YEARS)
    if missing:
        raise SystemExit(f"공휴일 표에 {missing}년이 없다 — scripts/sim/kr_holidays.py 에 그해 공휴일을 넣어야 한다")


def is_day_off(d: date) -> bool:
    """토·일 또는 공휴일."""
    return d.weekday() >= 5 or holiday_name(d) is not None


def day_type_of(d: date) -> str:
    return "weekend" if is_day_off(d) else "weekday"
