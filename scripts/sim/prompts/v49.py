"""후보 v49 — v45 에 시간 규칙 문장만 넣는다. 예시는 건드리지 않는다.

v46 은 두 가지를 함께 했다 — 검사되는 규칙을 문장으로 적고, 예시를 시각순으로
정렬했다. v47 라운드에서 그 조합이 간격 위반을 11건에서 25건으로 늘렸고,
정렬 쪽이 범인으로 보였다(예시에서 40분 이하로 붙은 쌍 4 → 7).

그렇다면 **문장 쪽은 무죄일 수 있다.** 이 후보가 그것만 따로 잰다.

    넣는다   "다음 이벤트의 `time` 은 앞 이벤트의 `time` 보다 최소 20분 뒤"
    안 넣는다  예시 정렬 · 마무리 예시

프롬프트는 "이벤트 간 최소 체류 20분" 이라고 적는데 검사기는 시작 시각 사이의
간격을 잰다. 스무 분을 머물러도 다음 `time` 이 15분 뒤면 위반이다. 있는 문장과
검사되는 규칙이 다르다는 사실 자체는 그대로다 — 이 후보는 그 사실만 고친다.

v48 이 마무리 예시만, 이 후보가 시간 규칙 문장만 맡는다. 셋을 갈라야 무엇이
무엇을 움직였는지 말할 수 있다.
"""
from __future__ import annotations

from .p012 import format_dawn_blocks  # noqa: F401  (본문 공통)
from .v45 import SYSTEM_PROMPT as _V45

DWELL_OLD = '- 이벤트 간 최소 체류 20분.'
DWELL_NEW = ('- 이벤트 간 최소 체류 20분. 그리고 **다음 이벤트의 `time` 은 앞 이벤트의 `time` '
             '보다\n  최소 20분 뒤**여야 한다 — 시각은 하루 동안 뒤로 가지 않는다.')


def build() -> str:
    s = _V45
    if DWELL_OLD not in s:
        raise ValueError('v45 본문이 바뀌었다 — 체류 규칙 줄을 찾지 못했다')
    return s.replace(DWELL_OLD, DWELL_NEW, 1)


SYSTEM_PROMPT = build()
